/** Deterministic, shared by UI and server. Program names never imply API capabilities. */
export function buildActionPlan(raw: AutomationInput, d: DiagnosisInput, labor?: LaborInput) {
  const i = applyDiagnosis(raw, d);
  const recommendation = recommend(i, d);
  const humanControl = needsHumanControl(d) || i.humanReview;
  const unknown = i.data === "unknown" || i.load === "unknown" || d.goal === "unknown" || d.errorImpact === "unknown" || (!d.systems.includes("manual") && i.api !== "yes") || i.processType === "custom";
  const steps = [
    ...opening[recommendation.approach].map((step, index) => index === 1 && i.interface && recommendation.approach !== "Разработка приложения" ? step + " Проверить прототип экрана сотрудников." : step),
    goalChecks[d.goal],
    processPilot[i.processType],
    humanControl
      ? "Проверить ошибки на тестовых данных; назначить человека, подтверждающего результат до внешних действий."
      : "Протестировать ошибки и согласовать выборочную проверку результата сотрудником.",
    humanControl
      ? "Запустить ограниченный пилот под контролем человека; согласовать остановку, откат и сопровождение."
      : "После проверки запустить ограниченный пилот; согласовать остановку, откат и сопровождение.",
  ];
  const connection = d.systems.includes("manual")
    ? "Процесс выполняется вручную: проверить, какие данные нужно сначала оцифровать."
    : i.api === "yes"
      ? "Доступность обмена указана вами: подтвердить её документацией, правами и тестом подключения. Название программы не подтверждает API."
      : "Подключение не подтверждено: проверить выгрузку и штатные способы обмена. При их отсутствии пересмотреть подход.";
  const data = i.data === "unknown" ? "Состояние данных неизвестно: изучить примеры до оценки реализации."
    : i.data === "clean" ? "Проверить полноту, актуальность и права доступа даже для упорядоченных данных."
    : "Данные требуют подготовки: проверить пропуски, дубли и качество исходных материалов.";
  const impact = `Последствия ошибки: ${errorImpacts[d.errorImpact].toLowerCase()}. ` + (humanControl ? "До внешних действий нужно подтверждение человеком и возможность остановки." : "Согласовать порядок исправления и возврата к ручной работе.");
  const quality = recommendation.usesAI
    ? "ИИ может ошибаться: проверить реальные примеры, источники, защиту данных и передачу спорных случаев человеку."
    : i.interface ? "Отдельный экран требует проверки прав пользователей и прототипа; готовое решение ещё нужно сравнить."
    : "Проверить, покрывают ли выбранные правила все действия; исключения передавать сотруднику.";
  const scale = i.employees === 0 ? "Указано ноль сотрудников: уточнить участников процесса и ответственного за проверку."
    : i.load === "unknown" ? "Объём неизвестен: замерить частоту и пики до оценки трудоёмкости."
    : i.load === "high" ? "Проверить пиковую нагрузку, ограничения сервисов и восстановление после сбоев."
    : d.goal === "sales" ? "Рост продаж не гарантирован: отделить влияние пилота от других факторов."
    : d.goal === "unknown" || d.goal === "other" ? "Критерий успеха ещё не определён: согласовать его с владельцем процесса."
    : "Сравнить результат пилота с выбранной бизнес-целью и назначить ответственного за контроль.";
  const technicalLimits = [
    d.systems.includes("manual") ? "Сначала оцифровать исходные данные." : `Подключение: ${i.api}; подтвердить документацией и тестом.`,
    `Данные: ${i.data}; объём: ${i.load}; проверить качество и пики.`,
    humanControl ? "До внешних действий — подтверждение человеком, остановка и откат." : "Согласовать выборочную проверку и откат.",
    recommendation.usesAI ? "ИИ: проверить качество, источники и защиту данных на примерах." : "Потребность в ИИ не подтверждена.",
    i.interface ? "Проверить прототип и права доступа к экрану." : "Проверить исключения из правил обработки.",
  ];
  return {
    recommendation,
    process: processTypes[i.processType],
    goal: businessGoals[d.goal],
    systems: d.systems.map(s => systemOptions[s]),
    steps,
    checks: [connection, data, impact, quality, scale],
    humanControl,
    technicalLimits,
    uncertainty: unknown ? "Это предварительный план. Нужна техническая проверка неизвестных условий до подтверждения решения." : "Это предварительный план: реализуемость подтверждается после проверки систем и тестового сценария.",
    aiExplanation: recommendation.usesAI ? "ИИ рассматривается для смысловой обработки; качество ещё нужно подтвердить." : "Потребность в ИИ не подтверждена. Сначала проверьте правила, шаблоны и готовые средства.",
    economics: labor ? calculateLabor(labor) : null,
  };
}
