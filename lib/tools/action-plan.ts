  "Готовый SaaS-сервис": ["Сравнить готовые сервисы для выбранной задачи, их ограничения и условия доступа.", "Проверить на пробном доступе нужные действия и способы переноса данных."],
  "Интеграция существующих систем": ["Проверить способы подключения, права доступа и ограничения программ.", "Сопоставить поля, форматы и правила обмена; определить обработку повторов."],
  "Разработка приложения": ["Описать сценарии сотрудников и сравнить их с готовыми продуктами.", "Сделать прототип отдельного экрана и согласовать требования до разработки."],
  "ИИ-автоматизация": ["Собрать реальные примеры и правильные ответы для проверки качества ИИ.", "Проверить качество на отдельной тестовой выборке и задать границы ответов."],
  "Скрипт или небольшой внутренний инструмент": ["Описать правила одного повторяющегося действия и формат входных данных.", "Собрать небольшой тестовый инструмент с обработкой ошибок и повторного запуска."],
  "Обычная автоматизация": ["Проверить процесс и выделить действия, которые можно описать правилами.", "Подготовить шаблоны и один тестовый сценарий без предположений о подключении."],
