export const scenarioIds = fitnessScenarios.map((s) => s.id);
export const scenarioById = (id: ScenarioId) =>
  fitnessScenarios.find((s) => s.id === id)!;
export function industryScenarios(industry: Industry): IndustryScenario[] {
  if (industry === "fitness") return fitnessScenarios;
  return fitnessScenarios
    .filter((s) =>
      [
        "reporting",
        "transfer",
        "missed-leads",
        "onboarding",
        "sales-control",
      ].includes(s.id),
    )
    .map((s) => ({
      ...s,
      problem: s.problem.replaceAll("клубов", "подразделений"),
    }));
}
